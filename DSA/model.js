/*
The most important skill isn't memorizing solutions, but instead learning to look at a problem and
think:

What is the problem asking?
        ↓
What would the brute-force solution be?
        ↓
What makes that solution inefficient?
        ↓
What data structure/pattern could remove that work?
        ↓
Implement it
        ↓
Analyze Time + Space Complexity

When analyzing time and space complexity always go based on the worst case scenario.


In general:

Array look up -> O(n) - worst case every element is inspected.
Set/Hash look up -> O(1) - hash based look up or constant time.

Brute force saves memory but does more work. The Set solution uses more memory to avoid repeated
work.

In simple terms we trade space for time.
*/
